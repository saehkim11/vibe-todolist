begin;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('task-images', 'task-images', false, 5242880, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update set public = false, file_size_limit = 5242880,
  allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp'];

create table if not exists public.task_attachments (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.tasks(id) on delete cascade,
  user_id uuid not null default auth.uid() references public.profiles(id),
  storage_path text not null unique,
  file_name text not null,
  created_at timestamptz not null default now(),
  constraint task_attachments_name_not_blank check (char_length(btrim(file_name)) > 0)
);

create index if not exists task_attachments_task_id_idx on public.task_attachments(task_id);
alter table public.task_attachments enable row level security;
revoke all on public.task_attachments from anon, authenticated;
grant select, insert, delete on public.task_attachments to authenticated;
grant usage, select on sequence public.task_attachments_id_seq to authenticated;

create policy task_attachments_select_visible on public.task_attachments for select to authenticated using (
  exists (select 1 from public.tasks t where t.id = task_id and (t.team_id = public.current_team_id() or public.is_my_subordinate(t.assignee_id)))
);
create policy task_attachments_insert_same_team on public.task_attachments for insert to authenticated with check (
  user_id = auth.uid() and exists (select 1 from public.tasks t where t.id = task_id and t.team_id = public.current_team_id())
);
create policy task_attachments_delete_own on public.task_attachments for delete to authenticated using (user_id = auth.uid());

create policy task_images_select_visible on storage.objects for select to authenticated using (
  bucket_id = 'task-images' and exists (select 1 from public.task_attachments a join public.tasks t on t.id = a.task_id where a.storage_path = name and (t.team_id = public.current_team_id() or public.is_my_subordinate(t.assignee_id)))
);
create policy task_images_insert_own on storage.objects for insert to authenticated with check (
  bucket_id = 'task-images' and exists (select 1 from public.task_attachments a join public.tasks t on t.id = a.task_id where a.storage_path = name and a.user_id = auth.uid() and t.team_id = public.current_team_id())
);
create policy task_images_delete_own on storage.objects for delete to authenticated using (
  bucket_id = 'task-images' and exists (select 1 from public.task_attachments a where a.storage_path = name and a.user_id = auth.uid())
);
commit;
