  on public.task_comments (task_id);
create index if not exists task_comments_user_id_idx
  on public.task_comments (user_id);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  task_id bigint not null references public.tasks(id) on delete cascade,
  type text not null default 'task_completed',
  message text not null,
  is_read boolean not null default false,
  created_at timestamptz not null default now(),
  constraint notifications_type_allowed check (type = 'task_completed'),
  constraint notifications_message_not_blank check (char_length(btrim(message)) > 0),
  constraint notifications_one_completion_per_recipient unique (recipient_id, task_id, type)
);

