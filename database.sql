-- 업무 생성·수정 시 팀 관계와 역할별 변경 가능 항목을 검사합니다.
create or replace function public.validate_task_change()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_is_leader boolean := false;
  v_is_assignee boolean := false;
begin
  if not public.profile_belongs_to_team(new.assignee_id, new.team_id) then
    raise exception '담당자는 업무와 같은 팀의 구성원이어야 합니다.';
  end if;

  if not exists (
    select 1
    from public.profiles as creator
    where creator.id = new.created_by
      and creator.team_id = new.team_id
      and creator.is_leader = true
  ) then
    raise exception '업무 생성자는 해당 팀의 팀장이어야 합니다.';
  end if;

  -- SQL Editor 같은 관리자 실행은 초기 데이터 구성을 위해 아래 사용자 검사를 건너뜁니다.
  if v_user_id is null then
    return new;
  end if;

  if tg_op = 'INSERT' then
    if new.created_by <> v_user_id or not public.is_team_leader(new.team_id) then
      raise exception '업무는 해당 팀장만 생성할 수 있습니다.';
    end if;

    return new;
  end if;

  v_is_leader := public.is_team_leader(old.team_id);
  v_is_assignee := old.assignee_id = v_user_id;

  if new.team_id is distinct from old.team_id
    or new.created_by is distinct from old.created_by
    or new.created_at is distinct from old.created_at then
    raise exception '업무의 팀, 생성자 및 생성 시각은 변경할 수 없습니다.';
  end if;

  if new.assignee_id is distinct from old.assignee_id and not v_is_leader then
    raise exception '업무 재배분은 해당 팀장만 할 수 있습니다.';
  end if;

  if (
    new.title is distinct from old.title
    or new.description is distinct from old.description
    or new.task_date is distinct from old.task_date
    or new.assignee_id is distinct from old.assignee_id
  ) and not v_is_leader then
    raise exception '업무 내용과 담당자는 해당 팀장만 변경할 수 있습니다.';
  end if;

  if (
    new.status is distinct from old.status
    or new.assignee_memo is distinct from old.assignee_memo
  ) and not v_is_assignee then
    raise exception '상태와 담당자 메모는 현재 담당자만 변경할 수 있습니다.';
  end if;

  return new;
end;
$$;

revoke all on function public.validate_task_change() from public;
revoke all on function public.validate_task_change() from anon, authenticated;

