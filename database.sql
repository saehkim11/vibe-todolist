as $$
  select p.team_id
  from public.profiles as p
  where p.id = auth.uid();
$$;

create or replace function public.is_team_leader(p_team_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles as p
    where p.id = auth.uid()
      and p.team_id = p_team_id
      and p.is_leader = true
  );
$$;

