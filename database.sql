-- Auth 가입 시 공개 프로필 기본 행을 만듭니다.
-- 팀과 팀장 여부는 가입 정보로 받지 않고 관리자가 나중에 배정합니다.
create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_display_name text;
begin
  v_display_name := nullif(btrim(new.raw_user_meta_data ->> 'display_name'), '');

  if v_display_name is null then
    v_display_name := split_part(coalesce(new.email, new.id::text), '@', 1);
  end if;

  insert into public.profiles (id, login_id, display_name)
  values (new.id, lower(new.email), v_display_name)
  on conflict (id) do nothing;

  return new;
end;
$$;

revoke all on function public.handle_new_auth_user() from public;
revoke all on function public.handle_new_auth_user() from anon, authenticated;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_auth_user();

