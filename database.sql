create table if not exists public.teams (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now(),
  constraint teams_name_not_blank check (char_length(btrim(name)) > 0)
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  login_id text not null unique,
  display_name text not null,
  team_id bigint references public.teams(id),
  is_leader boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_login_id_not_blank check (char_length(btrim(login_id)) > 0),
  constraint profiles_display_name_not_blank check (char_length(btrim(display_name)) > 0)
);

-- 한 팀에 팀장은 최대 한 명만 지정할 수 있습니다.
create unique index if not exists profiles_one_leader_per_team_idx
  on public.profiles (team_id)
  where is_leader = true and team_id is not null;

create index if not exists profiles_team_id_idx
  on public.profiles (team_id);

create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  team_id bigint not null references public.teams(id),
  title text not null,
  description text not null,
  task_date date not null,
  assignee_id uuid not null references public.profiles(id),
  created_by uuid not null default auth.uid() references public.profiles(id),
  status text not null default 'start_before',
  assignee_memo text not null default '',
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint tasks_title_length check (
    char_length(btrim(title)) between 1 and 200
  ),
  constraint tasks_description_not_blank check (
    char_length(btrim(description)) > 0
  ),
  constraint tasks_status_allowed check (
    status in ('start_before', 'in_progress', 'completed')
  )
);

create index if not exists tasks_team_id_idx
  on public.tasks (team_id);
create index if not exists tasks_assignee_id_idx
  on public.tasks (assignee_id);
create index if not exists tasks_task_date_idx
  on public.tasks (task_date);
create index if not exists tasks_status_idx
  on public.tasks (status);

create table if not exists public.task_comments (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.tasks(id) on delete cascade,
  user_id uuid not null default auth.uid() references public.profiles(id),
  content text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint task_comments_content_length check (
    char_length(btrim(content)) between 1 and 1000
  )
