-- 상태 완료 시각과 팀장 알림을 자동 처리합니다.
create or replace function public.prepare_task_status()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.status = 'completed' and old.status is distinct from 'completed' then
    new.completed_at := now();
  elsif new.status <> 'completed' and old.status = 'completed' then
    new.completed_at := null;
  end if;

  return new;
end;
$$;

revoke all on function public.prepare_task_status() from public;
revoke all on function public.prepare_task_status() from anon, authenticated;

drop trigger if exists tasks_prepare_status on public.tasks;
create trigger tasks_prepare_status
before update on public.tasks
for each row execute function public.prepare_task_status();

create or replace function public.notify_team_leader_on_completion()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_leader_id uuid;
  v_assignee_name text;
begin
  if new.status = 'completed' and old.status is distinct from 'completed' then
    select p.id
      into v_leader_id
    from public.profiles as p
    where p.team_id = new.team_id
      and p.is_leader = true;

    select p.display_name
      into v_assignee_name
    from public.profiles as p
    where p.id = new.assignee_id;

    if v_leader_id is not null then
      insert into public.notifications (
        recipient_id,
        task_id,
        type,
        message,
        is_read,
        created_at
      )
      values (
        v_leader_id,
        new.id,
        'task_completed',
        coalesce(v_assignee_name, '담당자') || '님이 [' || new.title || '] 업무를 완료했습니다.',
        false,
        now()
      )
      on conflict (recipient_id, task_id, type)
      do update set
        message = excluded.message,
        is_read = false,
        created_at = excluded.created_at;
    end if;
  end if;

  return new;
end;
$$;

revoke all on function public.notify_team_leader_on_completion() from public;
revoke all on function public.notify_team_leader_on_completion() from anon, authenticated;

drop trigger if exists tasks_notify_completion on public.tasks;
create trigger tasks_notify_completion
after update on public.tasks
for each row execute function public.notify_team_leader_on_completion();

