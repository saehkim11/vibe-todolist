-- 단체 메모 기능: Supabase SQL Editor에서 한 번 실행합니다.
begin;
create table if not exists public.memo_rooms (
  id bigint generated by default as identity primary key,
  title text not null,
  created_by uuid not null default auth.uid() references public.profiles(id),
  created_at timestamptz not null default now(),
  constraint memo_rooms_title check (char_length(btrim(title)) between 1 and 100)
);
create table if not exists public.memo_participants (
  room_id bigint not null references public.memo_rooms(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (room_id, user_id)
);
create table if not exists public.memo_messages (
  id bigint generated by default as identity primary key,
  room_id bigint not null references public.memo_rooms(id) on delete cascade,
  user_id uuid not null default auth.uid() references public.profiles(id),
  content text not null,
  created_at timestamptz not null default now(),
  constraint memo_messages_content check (char_length(btrim(content)) between 1 and 2000)
);
alter table public.memo_rooms enable row level security;
alter table public.memo_participants enable row level security;
alter table public.memo_messages enable row level security;
create or replace function public.is_memo_participant(p_room_id bigint) returns boolean language sql stable security definer set search_path='' as $$ select exists (select 1 from public.memo_participants where room_id=p_room_id and user_id=auth.uid()) $$;
grant execute on function public.is_memo_participant(bigint) to authenticated;
grant select,insert on public.memo_rooms to authenticated;
grant select,insert on public.memo_participants to authenticated;
grant select,insert on public.memo_messages to authenticated;
grant usage,select on sequence public.memo_rooms_id_seq, public.memo_messages_id_seq to authenticated;
create policy memo_rooms_select on public.memo_rooms for select to authenticated using (public.is_memo_participant(id));
create policy memo_rooms_insert on public.memo_rooms for insert to authenticated with check (created_by=auth.uid());
create policy memo_participants_select on public.memo_participants for select to authenticated using (public.is_memo_participant(room_id));
create policy memo_participants_insert on public.memo_participants for insert to authenticated with check (user_id=auth.uid() or public.is_memo_participant(room_id));
create policy memo_messages_select on public.memo_messages for select to authenticated using (public.is_memo_participant(room_id));
create policy memo_messages_insert on public.memo_messages for insert to authenticated with check (user_id=auth.uid() and public.is_memo_participant(room_id));
commit;
